import { useCallback, useEffect, useState } from 'react'
import { Link, NavLink, Route, Routes, useLocation, useNavigate, useParams } from 'react-router-dom'
import { useDropzone } from 'react-dropzone'
import {
  Activity, AlertCircle, ArrowDownToLine, ArrowRight, Check, ChevronLeft,
  ChevronRight, Clock3, FileText, HeartPulse, LayoutDashboard, LoaderCircle, LogIn,
  LogOut, Plus, RefreshCw, ShieldCheck, Trash2, Upload, UserRound, X,
} from 'lucide-react'
import { api, documentKindLabel, documentStatusLabel, formatDate } from './lib/api'
import { authEnabled, beginSignIn, completeSignIn, currentAccessToken, signOut } from './lib/auth'
import type { ApiDocument, DocumentKind, DocumentListItem, Profile, TimelineEvent } from './types'
import { I18nProvider, languageOptions, normalizeLanguage, translate, useI18n } from './i18n'

const disclaimer = 'Disclaimer: This summary is generated by AI for informational purposes only and is not a substitute for professional medical advice, diagnosis, or treatment. Always consult your doctor or qualified healthcare provider.'
type Toast = { text: string; error?: boolean }

function App() {
  const location = useLocation()
  const navigate = useNavigate()
  const [token, setToken] = useState<string | null>(currentAccessToken())
  const [authReady, setAuthReady] = useState(false)
  const [authError, setAuthError] = useState('')
  const [documents, setDocuments] = useState<DocumentListItem[]>([])
  const [events, setEvents] = useState<TimelineEvent[]>([])
  const [profile, setProfile] = useState<Profile | null>(null)
  const [loading, setLoading] = useState(true)
  const [busy, setBusy] = useState(false)
  const [toast, setToast] = useState<Toast | null>(null)
  const authOn = authEnabled()
  const language = normalizeLanguage(profile?.preferred_language)
  const tr = (message: string, values?: Record<string, string | number>) => translate(language, message, values)

  useEffect(() => {
    document.documentElement.lang = language
    document.title = `Carefolio — ${translate(language, 'Your health, in context')}`
  }, [language])

  const refresh = useCallback(async () => {
    if (authOn && !currentAccessToken()) {
      setLoading(false)
      setToken(null)
      return
    }
    setLoading(true)
    try {
      const [documentPage, eventPage, userProfile] = await Promise.all([
        api.listDocuments(), api.getTimeline(), api.getProfile(),
      ])
      setDocuments(documentPage.items)
      setEvents(eventPage.items)
      setProfile(userProfile)
    } catch (error) {
      setToast({ text: error instanceof Error ? error.message : tr('Could not load your health records.'), error: true })
    } finally {
      setLoading(false)
    }
  }, [authOn, language])

  useEffect(() => {
    let active = true
    completeSignIn().then((accessToken) => {
      if (active) {
        setToken(accessToken)
        setAuthReady(true)
      }
    }).catch((error: unknown) => {
      if (active) {
        setAuthError(error instanceof Error ? error.message : 'Sign-in failed.')
        setAuthReady(true)
      }
    })
    return () => { active = false }
  }, [])

  useEffect(() => {
    if (!authReady || (authOn && !token)) {
      if (authReady) setLoading(false)
      return
    }
    void refresh()
  }, [authReady, authOn, token, refresh])

  useEffect(() => {
    if (!documents.some((doc) => doc.status === 'queued' || doc.status === 'processing') || (authOn && !token)) return
    const timer = window.setInterval(() => { void refresh() }, 5000)
    return () => window.clearInterval(timer)
  }, [documents, authOn, token, refresh])

  useEffect(() => {
    if (!authOn || !token) return
    const timer = window.setInterval(() => {
      if (!currentAccessToken()) setToken(null)
    }, 30_000)
    return () => window.clearInterval(timer)
  }, [authOn, token])

  useEffect(() => {
    if (!toast) return
    const timer = window.setTimeout(() => setToast(null), 6000)
    return () => window.clearTimeout(timer)
  }, [toast])

  const upload = useCallback(async (file: File) => {
    setBusy(true)
    setToast(null)
    try {
      const accepted = await api.upload(file)
      await refresh()
      setToast({ text: tr('{file} uploaded. Processing status: {status}.', { file: file.name, status: localizedStatus(accepted.status, tr) }) })
      navigate(`/documents/${accepted.document_id}`)
    } catch (error) {
      setToast({ text: error instanceof Error ? error.message : tr('Upload failed.'), error: true })
    } finally {
      setBusy(false)
    }
  }, [refresh, navigate, language])

  const title = tr(location.pathname.startsWith('/documents') ? 'Document details'
    : location.pathname === '/timeline' ? 'Your timeline'
      : location.pathname === '/profile' ? 'Your profile' : 'Your health, in context')

  const login = async () => {
    setAuthError('')
    try { await beginSignIn() } catch (error) {
      setAuthError(error instanceof Error ? error.message : tr('Could not begin sign-in.'))
    }
  }

  if (!authReady) return <div className="live-loading"><LoaderCircle className="spin" /> {tr('Preparing your secure session…')}</div>
  if (authOn && !token) return <I18nProvider language={language}><main className="auth-screen"><div className="auth-card"><span className="brand-mark"><HeartPulse size={22} /></span><h1>{tr('Welcome to Carefolio')}</h1><p>{tr('Sign in to view and manage your private health documents.')}</p>{authError && <div className="live-error">{authError}</div>}<button className="button button-primary" onClick={() => void login()}><LogIn size={17} /> {tr('Sign in with Microsoft')}</button><small>{tr('Your sign-in is handled by your configured Entra External ID tenant.')}</small></div></main></I18nProvider>

  const changeLanguage = async (value: string) => {
    const next = normalizeLanguage(value)
    if (!profile || next === language) return
    try {
      const updated = await api.updateProfile({ preferred_language: next })
      setProfile(updated)
      setToast({ text: translate(next, 'Language preference saved.') })
    } catch (error) {
      setToast({ text: error instanceof Error ? error.message : tr('Could not save your profile.'), error: true })
    }
  }

  return <I18nProvider language={language}><div className="app-shell">
    <aside className="sidebar">
      <Link className="brand" to="/" aria-label={tr('Carefolio home')}><span className="brand-mark"><HeartPulse size={21} strokeWidth={2.4} /></span><span>carefolio<span className="brand-dot">.</span></span></Link>
      <div className="workspace-label">{tr('YOUR SPACE')}</div>
      <nav className="main-nav" aria-label={tr('Main navigation')}>
        <NavLink to="/" end className={({ isActive }) => `nav-item ${isActive ? 'active' : ''}`}><LayoutDashboard size={18} /> {tr('Overview')}</NavLink>
        <NavLink to="/timeline" className={({ isActive }) => `nav-item ${isActive ? 'active' : ''}`}><Clock3 size={18} /> {tr('Timeline')} <span className="nav-count">{events.length}</span></NavLink>
        <a href="/#documents" className="nav-item"><FileText size={18} /> {tr('Documents')}</a>
      </nav>
      <div className="sidebar-divider" /><div className="workspace-label">{tr('PREFERENCES')}</div>
      <nav className="main-nav"><NavLink to="/profile" className={({ isActive }) => `nav-item ${isActive ? 'active' : ''}`}><UserRound size={18} /> {tr('My profile')}</NavLink></nav>
      <div className="sidebar-bottom"><div className="privacy-card"><span className="privacy-icon"><ShieldCheck size={17} /></span><div><strong>{tr('Your health stays yours')}</strong><span>{tr('Your documents are private to your account.')}</span></div></div><div className="account-row"><span className="avatar">{initials(profile?.display_name)}</span><span className="account-name"><strong>{profile?.display_name || tr('Your account')}</strong><small>{authOn ? tr('Entra account') : tr('Local demo account')}</small></span></div></div>
    </aside>
    <main className="main-area">
      <header className="topbar"><div className="breadcrumb"><span>{tr('My health')}</span><ChevronRight size={15} /><strong>{title}</strong></div><div className="topbar-actions"><label className="language-picker"><span className="sr-only">{tr('Interface language')}</span><select aria-label={tr('Interface language')} value={language} onChange={(event) => void changeLanguage(event.target.value)}>{languageOptions.map((option) => <option value={option.code} key={option.code}>{option.name}</option>)}</select></label><span className={`connection-label ${authOn ? 'secure' : ''}`}>{authOn ? tr('Signed in') : tr('Local demo')}</span>{authOn && <button className="icon-button" aria-label={tr('Sign out')} title={tr('Sign out')} onClick={() => { setToken(null); setDocuments([]); setEvents([]); setProfile(null); void signOut() }}><LogOut size={17} /></button>}<button className="icon-button" aria-label={tr('Refresh records')} title={tr('Refresh')} onClick={() => void refresh()}><RefreshCw size={16} /></button></div></header>
      {toast && <div className={`live-toast ${toast.error ? 'error' : ''}`} role="status"><span>{toast.error ? <AlertCircle size={16} /> : <Check size={16} />}{toast.text}</span><button onClick={() => setToast(null)} aria-label={tr('Dismiss')}><X size={15} /></button></div>}
      <Routes>
        <Route path="/" element={<Dashboard documents={documents} events={events} loading={loading} busy={busy} onUpload={upload} />} />
        <Route path="/timeline" element={<TimelinePage events={events} loading={loading} onUpdated={(item) => setEvents((current) => current.map((event) => event.id === item.id ? item : event))} onDeleted={(id) => setEvents((current) => current.filter((event) => event.id !== id))} />} />
        <Route path="/documents/:id" element={<DocumentPage language={language} onChanged={() => void refresh()} onDeleted={() => { void refresh(); navigate('/') }} onMessage={setToast} />} />
        <Route path="/profile" element={<ProfilePage profile={profile} loading={loading} onSaved={setProfile} onMessage={setToast} />} />
        <Route path="*" element={<Dashboard documents={documents} events={events} loading={loading} busy={busy} onUpload={upload} />} />
      </Routes>
      <footer className="app-footer"><span>{tr('Carefolio helps organize health records.')}</span><span><ShieldCheck size={13} /> {tr('Use synthetic or de-identified documents')}</span></footer>
    </main>
  </div></I18nProvider>
}

