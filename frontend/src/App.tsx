    <section className="hero-card"><div className="hero-copy"><span className="hero-kicker"><Activity size={14} /> {t('HEALTH DOCUMENT ORGANIZER')}</span><h2>{t('A clearer picture,\none record at a time.')}</h2><p>{t('Upload a health document to organize its contents and, when configured, create a cautious summary for you to review.')}</p><a className="text-link" href="#documents">{t('Explore your records')} <ArrowRight size={15} /></a></div><div className="hero-art" aria-hidden="true"><div className="orbit orbit-one" /><div className="orbit orbit-two" /><div className="art-center"><HeartPulse size={31} /></div><div className="art-chip chip-top">{t('Private records')}</div><div className="art-chip chip-bottom">{t('Review every result')}</div></div></section>
